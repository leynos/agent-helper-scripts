"""Insert the canonical provenance note under the first heading.

The note is the file's record of which upstream revision it came from. It is
inserted in one place, after the first level-one heading outside fenced code,
so a later run and a reviewer both find it at the same offset. A source that
already carries it is refused, because converting a vendored copy again would
stack a second note.
"""

from __future__ import annotations

import re

from .config import VendorConfig, fail, project_name
from .masking import fence_line_flags

#: Canonical note placed after the first level-one heading. The marker
#: sentence is stable so a later run, or a reviewer, can recognize an already
#: vendored file without guessing at the wording.
NOTE_TEMPLATE = (
    "> **Imported from {project} `{tag}`.** Source:\n"
    "> <https://github.com/{repository}/tree/{tag}>.\n"
    "> This file is a verbatim upstream import generated by\n"
    "> `scripts/vendor_tagged_guides_cli.py`; do not edit it by hand. Re-run that\n"
    "> script against a new tag to refresh it.\n"
)

#: Stable prefix of :data:`NOTE_TEMPLATE`. A source carrying it is already a
#: vendored copy, so converting it again would stack a second note.
IMPORT_MARKER = "**Imported from "

_H1 = re.compile(r" {0,3}#[ \t]+[^\n]*")


def render_note(config: VendorConfig) -> str:
    """Render the canonical import note for one configuration.

    Parameters
    ----------
    config
        Import description.

    Returns
    -------
    str
        Pre-wrapped blockquote, ending with a newline.
    """
    return NOTE_TEMPLATE.format(
        project=project_name(config),
        tag=config.tag,
        repository=config.repository,
    )


def insert_note(text: str, config: VendorConfig) -> str:
    """Insert the canonical note after the first level-one heading.

    Parameters
    ----------
    text
        Converted document.
    config
        Import description.

    Returns
    -------
    str
        Document with the note separated by one blank line on each side.

    Raises
    ------
    VendorError
        If the document has no level-one heading.
    """
    lines = text.split("\n")
    flags = fence_line_flags(lines)
    heading = next(
        (
            index
            for index, line in enumerate(lines)
            if not flags[index] and _H1.fullmatch(line)
        ),
        None,
    )
    if heading is None:
        fail("source document has no level-one heading")
    body = lines[heading + 1 :]
    while body and not body[0].strip():
        body.pop(0)
    before = "\n".join(lines[: heading + 1])
    return f"{before}\n\n{render_note(config)}\n" + "\n".join(body)