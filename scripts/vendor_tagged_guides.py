"""Vendor an upstream guide at a pinned tag into a consuming repository.

A vendored guide is a verbatim copy of an upstream document at one known tag,
not a merge of the upstream text into a repository-owned document. Three
transformations make that copy usable in a checkout:

- every relative link becomes an absolute URL pinned to the tag, so the copy
  cannot silently follow the upstream default branch;
- links between two guides that are imported together stay local, so they
  resolve inside the consuming repository;
- a canonical "Imported from" note is inserted after the first heading, and
  bounded MD013 exemptions are added where the consumer's formatter cannot
  break a line.

The transformations are pure standard-library functions, so a test can call
them without a formatter or a process. `vendor()` composes them with an
injected ``format_files`` callable; the sibling ``vendor_tagged_guides_cli``
module supplies the Cyclopts front end and the cuprum process boundary.

Examples
--------
Vendor two cuprum guides from a checkout of the upstream ``docs/`` directory::

    uv run --script scripts/vendor_tagged_guides_cli.py \\
        --tag v0.2.0-beta2 \\
        --repository leynos/cuprum \\
        --source ../cuprum/docs \\
        --output docs \\
        --map users-guide.md=cuprum-users-guide.md \\
        --map v0-2-0-migration-guide.md=cuprum-v0-2-0-migration-guide.md

The core module imports nothing beyond the standard library, so it remains
importable under Python 3.13 even though the front end targets Python 3.14.
"""

from __future__ import annotations

from collections.abc import Callable, Iterable, Sequence
from dataclasses import dataclass
import posixpath
import re
from pathlib import Path

#: Repository-relative directory the upstream sources live in, used to build
#: absolute URLs for relative links.
DEFAULT_SOURCE_PATH = "docs"

#: Prose line length the consuming repository's Markdown gate enforces.
DEFAULT_LINE_LENGTH = 80

#: Line length the same gate allows inside fenced code blocks.
DEFAULT_CODE_LINE_LENGTH = 120

#: Canonical note placed after the first level-one heading. The marker
#: sentence is stable so a later run, or a reviewer, can recognize an already
#: vendored file without guessing at the wording.
NOTE_TEMPLATE = (
    "> **Imported from {project} `{tag}`.** Source:\n"
    "> <https://github.com/{repository}/tree/{tag}>.\n"
    "> This file is a verbatim upstream import generated by\n"
    "> `scripts/vendor_tagged_guides_cli.py`; do not edit it by hand. Re-run that\n"
    "> script against a new tag to refresh it.\n"
)

#: Stable prefix of :data:`NOTE_TEMPLATE`. A source carrying it is already a
#: vendored copy, so converting it again would stack a second note.
IMPORT_MARKER = "**Imported from "

#: Comment pair that brackets a block too long for the prose limit.
DISABLE_M013 = "<!-- markdownlint-disable MD013 -->"
ENABLE_M013 = "<!-- markdownlint-enable MD013 -->"

_REPOSITORY = re.compile(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+\Z")
_TAG = re.compile(r"[A-Za-z0-9][A-Za-z0-9._/+-]*\Z")
_SCHEME = re.compile(r"[A-Za-z][A-Za-z0-9+.-]*:")
_FENCE_OPEN = re.compile(r" {0,3}(`{3,}|~{3,})(.*)\Z")
_FENCE_CLOSE = re.compile(r" {0,3}(`{3,}|~{3,})\s*\Z")
_HEADING = re.compile(r" {0,3}(#{1,6})(?:[ \t]|\Z)")
_H1 = re.compile(r" {0,3}#[ \t]+[^\n]*")
_FOOTNOTE_DEFINITION = re.compile(r" {0,3}\[\^[^\]]+\]:")
_DEFINITION = re.compile(r"(?m)^ {0,3}\[([^\]]+)\]:[ \t]*")
_LIST_ITEM = re.compile(r" {0,3}(?:[-*+]|\d+[.)])[ \t]")
_THEMATIC_BREAK = re.compile(r" {0,3}([-*_])(?:[ \t]*\1){2,}[ \t]*\Z")
_TABLE_DELIMITER = re.compile(
    r" {0,3}\|?[ \t]*:?-{3,}:?[ \t]*(?:\|[ \t]*:?-{3,}:?[ \t]*)+\|?[ \t]*\Z"
)
_HTML_COMMENT_START = re.compile(r" {0,3}<!--")
_DISABLE_BLOCK = re.compile(
    r" {0,3}<!--\s*markdownlint-disable\s+MD013\s*-->\s*\Z"
)
_ENABLE_BLOCK = re.compile(
    r" {0,3}<!--\s*markdownlint-enable\s+MD013\s*-->\s*\Z"
)
_DISABLE_LINE = re.compile(
    r" {0,3}<!--\s*markdownlint-disable-line\s+MD013\s*-->\s*\Z"
)
_DISABLE_NEXT_LINE = re.compile(
    r" {0,3}<!--\s*markdownlint-disable-next-line\s+MD013\s*-->\s*\Z"
)


class VendorError(RuntimeError):
    """Report that a guide could not be converted as requested."""


#: Failures the front end reports as a one-line diagnostic rather than a
#: traceback. The tuple mirrors ``gate_runner.GATE_ERRORS``.
VENDOR_ERRORS = (VendorError,)


@dataclass(frozen=True)
class VendorConfig:
    """Describe one tagged import.

    Attributes
    ----------
    tag
        Upstream tag to pin, for example ``v0.2.0-beta2``.
    repository
        Upstream repository in ``owner/name`` form, without a host or scheme.
    source_directory
        Directory holding the upstream Markdown sources.
    output_directory
        Directory the converted files are written to.
    mappings
        ``(source filename, output filename)`` pairs, in output order.
    project
        Display name used by the import note. Defaults to the repository name.
    source_path
        Repository-relative directory of the sources, used to resolve relative
        links. Defaults to ``docs``.
    line_length
        Prose line length the consuming repository enforces.
    code_line_length
        Line length the consuming repository allows in fenced code.
    """

    tag: str
    repository: str
    source_directory: Path
    output_directory: Path
    mappings: tuple[tuple[str, str], ...]
    project: str = ""
    source_path: str = DEFAULT_SOURCE_PATH
    line_length: int = DEFAULT_LINE_LENGTH
    code_line_length: int = DEFAULT_CODE_LINE_LENGTH


def _fail(message: str) -> None:
    """Raise :class:`VendorError` with a one-line message.

    Parameters
    ----------
    message
        Explanation printed by the front end.

    Raises
    ------
    VendorError
        Always.
    """
    raise VendorError(message)


def _validate_relative_name(value: str, *, role: str) -> str:
    """Normalize one repository-relative path supplied by a caller.

    Parameters
    ----------
    value
        Path text to validate.
    role
        Short description used in the error message.

    Returns
    -------
    str
        The path with redundant separators removed.

    Raises
    ------
    VendorError
        If the path is empty, absolute, Windows-style, or escapes its root.
    """
    if not value:
        _fail(f"{role} must not be empty")
    if "\\" in value:
        _fail(f"{role} must use '/', not '\\': {value}")
    if value.startswith("/"):
        _fail(f"{role} must be relative: {value}")
    normalized = posixpath.normpath(value)
    if normalized == ".." or normalized.startswith("../"):
        _fail(f"{role} must stay inside its root: {value}")
    return normalized


def _validate_mapping(
    mappings: Sequence[tuple[str, str]], source_directory: Path
) -> None:
    """Check that every filename pair is usable before anything is written.

    Parameters
    ----------
    mappings
        Pairs supplied by the caller.
    source_directory
        Directory the source names are resolved against.

    Raises
    ------
    VendorError
        If a pair is empty, names a directory, repeats a side, or names a
        source that does not exist.
    """
    if not mappings:
        _fail("at least one source/output mapping is required")
    seen_sources: set[str] = set()
    seen_outputs: set[str] = set()
    for source_name, output_name in mappings:
        source_relative = _validate_relative_name(source_name, role="source name")
        output_relative = _validate_relative_name(output_name, role="output name")
        if posixpath.basename(output_relative) != output_relative:
            _fail(f"output name must be a bare filename: {output_name}")
        if not output_relative.endswith(".md"):
            _fail(f"output name must end in '.md': {output_name}")
        if source_relative in seen_sources:
            _fail(f"source is mapped more than once: {source_name}")
        if output_relative in seen_outputs:
            _fail(f"output is mapped more than once: {output_name}")
        source_file = source_directory / source_relative
        if not source_file.is_file():
            _fail(f"source file does not exist: {source_file}")
        seen_sources.add(source_relative)
        seen_outputs.add(output_relative)


def validate(config: VendorConfig) -> None:
    """Check every argument before the first file is written.

    Parameters
    ----------
    config
        Import description to check.

    Raises
    ------
    VendorError
        If the tag, repository, directory, limit, or mapping is unusable.
    """
    if not _REPOSITORY.fullmatch(config.repository):
        _fail(
            "repository must be 'owner/name' without a host or scheme: "
            f"{config.repository}"
        )
    if not _TAG.fullmatch(config.tag):
        _fail(f"tag is not a valid ref name: {config.tag}")
    if any(part in {"", ".", ".."} for part in config.tag.split("/")):
        _fail(f"tag is not a valid ref name: {config.tag}")
    if config.line_length < 1:
        _fail(f"line length must be positive: {config.line_length}")
    if config.code_line_length < 1:
        _fail(f"code line length must be positive: {config.code_line_length}")
    _validate_relative_name(config.source_path, role="source path")
    if not config.source_directory.is_dir():
        _fail(f"source directory does not exist: {config.source_directory}")
    if not config.output_directory.is_dir():
        _fail(f"output directory does not exist: {config.output_directory}")
    _validate_mapping(config.mappings, config.source_directory)


def _project_name(config: VendorConfig) -> str:
    """Return the note's project name, defaulting to the repository name.

    Parameters
    ----------
    config
        Import description.

    Returns
    -------
    str
        Explicit project name, or the repository's final path segment.
    """
    return config.project or config.repository.rsplit("/", 1)[-1]


def _masked_regions(text: str) -> list[bool]:
    """Mark text that link rewriting must leave byte for byte.

    Fenced code, inline code spans, footnote definitions, and HTML comments
    are protected. The returned list has one entry per character.

    Parameters
    ----------
    text
        Document to scan.

    Returns
    -------
    list[bool]
        ``True`` where a character is protected.
    """
    mask = [False] * len(text)
    lines = text.split("\n")
    offsets = [0]
    for line in lines:
        offsets.append(offsets[-1] + len(line) + 1)

    def mark(start: int, end: int) -> None:
        """Protect one half-open character range."""
        for index in range(max(start, 0), min(end, len(mask))):
            mask[index] = True

    def mark_lines(first: int, last: int) -> None:
        """Protect a half-open range of line numbers."""
        mark(offsets[first], offsets[last] if last < len(lines) else len(text))

    index = 0
    while index < len(lines):
        opening = _FENCE_OPEN.match(lines[index])
        if opening is None:
            index += 1
            continue
        character = opening.group(1)[0]
        length = len(opening.group(1))
        first = index
        index += 1
        while index < len(lines):
            closing = _FENCE_CLOSE.match(lines[index])
            index += 1
            if (
                closing is not None
                and closing.group(1)[0] == character
                and len(closing.group(1)) >= length
            ):
                break
        mark_lines(first, index)

    index = 0
    while index < len(lines):
        if not _FOOTNOTE_DEFINITION.match(lines[index]):
            index += 1
            continue
        first = index
        index += 1
        while index < len(lines):
            if lines[index].startswith(("    ", "\t")):
                index += 1
                continue
            if _FOOTNOTE_DEFINITION.match(lines[index]):
                index += 1
                continue
            if not lines[index].strip():
                lookahead = index
                while lookahead < len(lines) and not lines[lookahead].strip():
                    lookahead += 1
                if lookahead < len(lines) and (
                    lines[lookahead].startswith(("    ", "\t"))
                    or _FOOTNOTE_DEFINITION.match(lines[lookahead])
                ):
                    index = lookahead
                    continue
            break
        mark_lines(first, index)

    cursor = 0
    while True:
        start = text.find("<!--", cursor)
        if start < 0:
            break
        end = text.find("-->", start + 4)
        if end < 0:
            break
        mark(start, end + 3)
        cursor = end + 3

    # Code spans are found last, on characters the earlier passes left alive,
    # so backticks inside a fence or comment cannot open a span.
    cursor = 0
    while cursor < len(text):
        if mask[cursor] or text[cursor] != "`":
            cursor += 1
            continue
        run_start = cursor
        while cursor < len(text) and text[cursor] == "`":
            cursor += 1
        length = cursor - run_start
        closing = cursor
        while closing < len(text):
            if mask[closing] or text[closing] != "`":
                closing += 1
                continue
            run_end = closing
            while run_end < len(text) and text[run_end] == "`":
                run_end += 1
            if run_end - closing == length:
                mark(run_start, run_end)
                cursor = run_end
                break
            closing = run_end
        # An unmatched run is an ordinary literal; leave it and continue.
    return mask


def _skip_link_space(text: str, position: int) -> int | None:
    """Skip the whitespace Markdown allows inside a link's tail.

    Parameters
    ----------
    text
        Document being scanned.
    position
        Offset just after the opening delimiter.

    Returns
    -------
    int | None
        Offset of the next significant character, or ``None`` when more than
        one line ending intervenes and the construct is therefore not a link.
    """
    newlines = 0
    while position < len(text) and text[position] in " \t\n":
        if text[position] == "\n":
            newlines += 1
            if newlines > 1:
                return None
        position += 1
    return position


def _find_closing_bracket(text: str, position: int, mask: Sequence[bool]) -> int | None:
    """Find the ``]`` matching a label opener.

    Parameters
    ----------
    text
        Document being scanned.
    position
        Offset of the first character after the opener.
    mask
        Protected-character map.

    Returns
    -------
    int | None
        Offset of the matching ``]``, or ``None`` when the label is unclosed.
    """
    depth = 0
    while position < len(text):
        if mask[position]:
            position += 1
            continue
        character = text[position]
        if character == "\\":
            position += 2
            continue
        if character == "[":
            depth += 1
        elif character == "]":
            if depth == 0:
                return position
            depth -= 1
        position += 1
    return None


def _parse_destination(text: str, position: int) -> tuple[int, int, int] | None:
    """Read one inline-link or definition destination.

    Parameters
    ----------
    text
        Document being scanned.
    position
        Offset where the destination may start.

    Returns
    -------
    tuple[int, int, int] | None
        Start, end, and offset after the destination, or ``None`` when no
        destination can be read there.
    """
    if position >= len(text):
        return None
    if text[position] == "<":
        start = position + 1
        cursor = start
        while cursor < len(text) and text[cursor] not in ">\n":
            if text[cursor] == "\\":
                cursor += 1
            cursor += 1
        if cursor >= len(text) or text[cursor] != ">":
            return None
        return start, cursor, cursor + 1

    start = position
    depth = 0
    cursor = position
    while cursor < len(text):
        character = text[cursor]
        if character == "\\":
            cursor += 2
            continue
        if character == "(":
            depth += 1
        elif character == ")":
            if depth == 0:
                break
            depth -= 1
        elif character.isspace() or character in "<>":
            break
        cursor += 1
    if depth or cursor == start:
        return None
    return start, cursor, cursor


def _skip_title(text: str, position: int) -> int | None:
    """Skip an optional link title and the space after it.

    Parameters
    ----------
    text
        Document being scanned.
    position
        Offset just after the destination.

    Returns
    -------
    int | None
        Offset after the title, or ``None`` when a title is malformed.
    """
    cursor = position
    while cursor < len(text) and text[cursor] in " \t\n":
        cursor += 1
    if cursor >= len(text) or text[cursor] not in "\"'(":
        return cursor
    closer = ")" if text[cursor] == "(" else text[cursor]
    cursor += 1
    while cursor < len(text):
        if text[cursor] == "\\":
            cursor += 2
            continue
        if text[cursor] == closer:
            cursor += 1
            break
        cursor += 1
    else:
        return None
    while cursor < len(text) and text[cursor] in " \t\n":
        cursor += 1
    return cursor


def _parse_inline_link(
    text: str, position: int, mask: Sequence[bool]
) -> tuple[int, int, int] | None:
    """Read an inline link or image tail beginning at ``position``.

    Parameters
    ----------
    text
        Document being scanned.
    position
        Offset just after the label's ``]``.
    mask
        Protected-character map.

    Returns
    -------
    tuple[int, int, int] | None
        Destination start, destination end, and offset after the closing
        ``)``; ``None`` when the construct is not an inline link.
    """
    cursor = _skip_link_space(text, position)
    if cursor is None or cursor >= len(text) or text[cursor] != "(":
        return None
    cursor += 1
    cursor = _skip_link_space(text, cursor)
    if cursor is None:
        return None
    destination = _parse_destination(text, cursor)
    if destination is None:
        return None
    start, end, cursor = destination
    cursor = _skip_title(text, cursor)
    if cursor is None or cursor >= len(text) or text[cursor] != ")":
        return None
    if any(mask[index] for index in range(start, end)):
        return None
    return start, end, cursor + 1


def _destination_url(
    destination: str,
    *,
    config: VendorConfig,
    image: bool,
    source_name: str,
) -> str:
    """Rewrite one relative destination as a tag-pinned URL.

    Parameters
    ----------
    destination
        Destination exactly as Markdown wrote it.
    config
        Import description.
    image
        Whether the destination belongs to an image.
    source_name
        Repository-relative name of the source file being converted.

    Returns
    -------
    str
        The rewritten destination, or the original when it is absolute,
        scheme-relative, fragment-only, or already a URL.

    Raises
    ------
    VendorError
        If a relative destination escapes the upstream repository root.
    """
    if destination.startswith("#") or destination.startswith("//"):
        return destination
    if _SCHEME.match(destination):
        return destination
    path, _, fragment = destination.partition("#")
    path, _, query = path.partition("?")
    if not path:
        return destination

    trailing_slash = path.endswith("/")
    if path.startswith("/"):
        repository_path = posixpath.normpath(path.lstrip("/"))
    else:
        repository_path = posixpath.normpath(
            posixpath.join(config.source_path, path)
        )
    if repository_path == ".." or repository_path.startswith("../"):
        _fail(
            f"link in {source_name} escapes the upstream repository: "
            f"{destination}"
        )

    mappings = {
        posixpath.normpath(posixpath.join(config.source_path, name)): output
        for name, output in config.mappings
    }
    if repository_path in mappings:
        rewritten = mappings[repository_path]
    elif image:
        rewritten = (
            f"https://raw.githubusercontent.com/{config.repository}/"
            f"{config.tag}/{repository_path}"
        )
    elif trailing_slash:
        rewritten = (
            f"https://github.com/{config.repository}/tree/{config.tag}/"
            f"{repository_path}"
        )
    else:
        rewritten = (
            f"https://github.com/{config.repository}/blob/{config.tag}/"
            f"{repository_path}"
        )
    if query:
        rewritten += f"?{query}"
    if fragment:
        rewritten += f"#{fragment}"
    return rewritten


def _link_replacements(
    text: str,
    mask: Sequence[bool],
    config: VendorConfig,
    source_name: str,
) -> list[tuple[int, int, str]]:
    """Collect destination replacements for inline links and definitions.

    Parameters
    ----------
    text
        Document being scanned.
    mask
        Protected-character map.
    config
        Import description.
    source_name
        Repository-relative name of the source file being converted.

    Returns
    -------
    list[tuple[int, int, str]]
        ``(start, end, replacement)`` triples in document order.
    """
    replacements: list[tuple[int, int, str]] = []
    cursor = 0
    while cursor < len(text):
        if mask[cursor]:
            cursor += 1
            continue
        if text[cursor] != "[":
            cursor += 1
            continue
        image = cursor > 0 and text[cursor - 1] == "!" and not mask[cursor - 1]
        label_end = _find_closing_bracket(text, cursor + 1, mask)
        if label_end is None:
            cursor += 1
            continue
        parsed = _parse_inline_link(text, label_end + 1, mask)
        if parsed is None:
            cursor = label_end + 1
            continue
        start, end, after = parsed
        original = text[start:end]
        rewritten = _destination_url(
            original,
            config=config,
            image=image,
            source_name=source_name,
        )
        if rewritten != original:
            replacements.append((start, end, rewritten))
        cursor = after

    for match in _DEFINITION.finditer(text):
        if mask[match.start()] or match.group(1).startswith("^"):
            continue
        position = _skip_link_space(text, match.end())
        if position is None:
            continue
        parsed = _parse_destination(text, position)
        if parsed is None:
            continue
        start, end, _ = parsed
        if any(mask[index] for index in range(start, end)):
            continue
        original = text[start:end]
        rewritten = _destination_url(
            original,
            config=config,
            image=False,
            source_name=source_name,
        )
        if rewritten != original:
            replacements.append((start, end, rewritten))
    return replacements


def _apply_replacements(
    text: str, replacements: Iterable[tuple[int, int, str]]
) -> str:
    """Apply destination replacements without disturbing any other byte.

    Parameters
    ----------
    text
        Document to rewrite.
    replacements
        Spans and their replacements, in any order.

    Returns
    -------
    str
        Document with only the named spans replaced.
    """
    ordered = sorted(replacements, reverse=True)
    previous_start = len(text)
    for start, end, replacement in ordered:
        if end > previous_start:
            _fail("internal error: overlapping link replacements")
        text = text[:start] + replacement + text[end:]
        previous_start = start
    return text


def _note(config: VendorConfig) -> str:
    """Render the canonical import note for one configuration.

    Parameters
    ----------
    config
        Import description.

    Returns
    -------
    str
        Pre-wrapped blockquote, ending with a newline.
    """
    return NOTE_TEMPLATE.format(
        project=_project_name(config),
        tag=config.tag,
        repository=config.repository,
    )


def _insert_note(text: str, config: VendorConfig) -> str:
    """Insert the canonical note after the first level-one heading.

    Parameters
    ----------
    text
        Converted document.
    config
        Import description.

    Returns
    -------
    str
        Document with the note separated by one blank line on each side.

    Raises
    ------
    VendorError
        If the document has no level-one heading.
    """
    lines = text.split("\n")
    fence_flags = _fence_line_flags(lines)
    heading = next(
        (
            index
            for index, line in enumerate(lines)
            if not fence_flags[index] and _H1.fullmatch(line)
        ),
        None,
    )
    if heading is None:
        _fail("source document has no level-one heading")
    body = lines[heading + 1 :]
    while body and not body[0].strip():
        body.pop(0)
    before = "\n".join(lines[: heading + 1])
    return f"{before}\n\n{_note(config)}\n" + "\n".join(body)


def convert(text: str, config: VendorConfig, source_name: str = "") -> str:
    """Convert one upstream document into a vendored copy.

    Parameters
    ----------
    text
        Upstream Markdown, in any newline convention.
    config
        Import description.
    source_name
        Repository-relative source filename, used to resolve links between
        mapped guides. Defaults to the first mapping's source.

    Returns
    -------
    str
        Converted document with ``\\n`` newlines and one trailing newline.

    Raises
    ------
    VendorError
        If the source already carries the canonical note or has no level-one
        heading.
    """
    normalized = text.replace("\r\n", "\n").replace("\r", "\n")
    if IMPORT_MARKER in normalized:
        _fail("source already carries the canonical import marker")
    name = source_name or config.mappings[0][0]
    mask = _masked_regions(normalized)
    rewritten = _apply_replacements(
        normalized,
        _link_replacements(normalized, mask, config, name),
    )
    with_note = _insert_note(rewritten, config)
    return with_note.rstrip("\n") + "\n"


def _fence_line_flags(lines: Sequence[str]) -> list[bool]:
    """Mark lines that belong to a fenced code block.

    Parameters
    ----------
    lines
        Document lines, without newline characters.

    Returns
    -------
    list[bool]
        One flag per line; the fence markers themselves are included.
    """
    flags = [False] * len(lines)
    index = 0
    while index < len(lines):
        opening = _FENCE_OPEN.match(lines[index])
        if opening is None:
            index += 1
            continue
        character = opening.group(1)[0]
        length = len(opening.group(1))
        flags[index] = True
        index += 1
        while index < len(lines):
            closing = _FENCE_CLOSE.match(lines[index])
            flags[index] = True
            index += 1
            if (
                closing is not None
                and closing.group(1)[0] == character
                and len(closing.group(1)) >= length
            ):
                break
    return flags


def _table_line_flags(lines: Sequence[str]) -> list[bool]:
    """Mark lines that belong to a Markdown table.

    Markdownlint exempts tables from MD013, so the gate must not report them.

    Parameters
    ----------
    lines
        Document lines, without newline characters.

    Returns
    -------
    list[bool]
        One flag per table line, including the header and delimiter rows.
    """
    flags = [False] * len(lines)

    def mark(first: int, last: int) -> None:
        """Mark a half-open line range."""
        for index in range(first, min(last, len(flags))):
            flags[index] = True

    index = 0
    while index + 1 < len(lines):
        delimiter = _TABLE_DELIMITER.match(lines[index + 1])
        if delimiter is None or "|" not in lines[index]:
            index += 1
            continue
        first = index
        index += 2
        while index < len(lines) and lines[index].strip() and "|" in lines[index]:
            index += 1
        mark(first, index)
    return flags


def _exempt_lines(lines: Sequence[str]) -> set[int]:
    """Collect line numbers covered by an existing MD013 exemption.

    Parameters
    ----------
    lines
        Document lines, without newline characters.

    Returns
    -------
    set[int]
        Zero-based line numbers a later detection pass must ignore.
    """
    exempt: set[int] = set()
    disabled = False
    for index, line in enumerate(lines):
        if _DISABLE_BLOCK.match(line):
            disabled = True
            exempt.add(index)
            continue
        if _ENABLE_BLOCK.match(line):
            disabled = False
            exempt.add(index)
            continue
        if disabled:
            exempt.add(index)
        if _DISABLE_NEXT_LINE.match(line):
            exempt.add(index)
            exempt.add(index + 1)
        if _DISABLE_LINE.match(line):
            exempt.add(index)
    return exempt


def _is_blank(line: str) -> bool:
    """Say whether a line contains only whitespace."""
    return not line.strip()


def _is_block_starter(line: str) -> bool:
    """Say whether a line begins a block that ends a paragraph."""
    return bool(
        _HEADING.match(line)
        or _FENCE_OPEN.match(line)
        or line.lstrip().startswith(">")
        or _LIST_ITEM.match(line)
        or _THEMATIC_BREAK.match(line)
        or _HTML_COMMENT_START.match(line)
        or _TABLE_DELIMITER.match(line)
    )


def _is_indented(line: str) -> bool:
    """Say whether a line is indented enough to continue a list item."""
    return line.startswith(("  ", "\t"))


def _block_ranges(
    lines: Sequence[str], fence_flags: Sequence[bool], table_flags: Sequence[bool]
) -> tuple[list[tuple[int, int]], list[int]]:
    """Split a document into top-level blocks.

    The ranges let an exemption wrap the smallest paragraph, list, blockquote,
    table, or fenced block that contains an offending line.

    Parameters
    ----------
    lines
        Document lines, without newline characters.
    fence_flags
        Fenced-code map from :func:`_fence_line_flags`.
    table_flags
        Table map from :func:`_table_line_flags`.

    Returns
    -------
    tuple[list[tuple[int, int]], list[int]]
        Inclusive block ranges in document order, and an owner index per line
        (``-1`` for blank lines).
    """
    ranges: list[tuple[int, int]] = []
    owner = [-1] * len(lines)
    index = 0
    while index < len(lines):
        if _is_blank(lines[index]):
            index += 1
            continue
        if fence_flags[index]:
            start = index
            while index < len(lines) and fence_flags[index]:
                index += 1
            ranges.append((start, index - 1))
            continue
        if table_flags[index]:
            start = index
            while index < len(lines) and table_flags[index]:
                index += 1
            ranges.append((start, index - 1))
            continue
        if _HEADING.match(lines[index]):
            ranges.append((index, index))
            index += 1
            continue
        if _HTML_COMMENT_START.match(lines[index]):
            start = index
            while index < len(lines) and "-->" not in lines[index]:
                index += 1
            index = min(index + 1, len(lines))
            ranges.append((start, index - 1))
            continue
        if lines[index].lstrip().startswith(">"):
            start = index
            index += 1
            while index < len(lines) and lines[index].lstrip().startswith(">"):
                index += 1
            ranges.append((start, index - 1))
            continue
        if _THEMATIC_BREAK.match(lines[index]):
            ranges.append((index, index))
            index += 1
            continue
        if _LIST_ITEM.match(lines[index]):
            start = index
            cursor = index
            while cursor + 1 < len(lines):
                following = lines[cursor + 1]
                if _is_blank(following):
                    lookahead = cursor + 1
                    while lookahead < len(lines) and _is_blank(lines[lookahead]):
                        lookahead += 1
                    if lookahead < len(lines) and (
                        _LIST_ITEM.match(lines[lookahead])
                        or _is_indented(lines[lookahead])
                    ):
                        cursor = lookahead - 1
                        continue
                    break
                if _LIST_ITEM.match(following) or _is_indented(following):
                    cursor += 1
                    continue
                if not _is_block_starter(following):
                    cursor += 1
                    continue
                break
            ranges.append((start, cursor))
            index = cursor + 1
            continue
        start = index
        cursor = index
        while (
            cursor + 1 < len(lines)
            and not _is_blank(lines[cursor + 1])
            and not _is_block_starter(lines[cursor + 1])
        ):
            cursor += 1
        ranges.append((start, cursor))
        index = cursor + 1

    for block, (start, end) in enumerate(ranges):
        for line_number in range(start, end + 1):
            owner[line_number] = block
    return ranges, owner


def _is_too_long(line: str, limit: int) -> bool:
    """Apply MD013's non-strict length check to one line.

    MD013 allows a long line when it has no whitespace beyond the limit, which
    is how long URLs stay legal. Trailing whitespace is not counted, matching
    the rule's non-strict mode.

    Parameters
    ----------
    line
        Line to check, without its newline.
    limit
        Maximum permitted length.

    Returns
    -------
    bool
        ``True`` when the line violates the rule.
    """
    stripped = line.rstrip()
    if len(stripped) <= limit:
        return False
    return any(character.isspace() for character in stripped[limit:])


def long_lines(
    text: str,
    *,
    line_length: int = DEFAULT_LINE_LENGTH,
    code_line_length: int = DEFAULT_CODE_LINE_LENGTH,
) -> tuple[int, ...]:
    """List lines that the consumer's Markdown gate would report.

    Headings and tables are skipped because the shared configuration disables
    their length checks. Lines already covered by an MD013 exemption are
    skipped so the function stays idempotent.

    Parameters
    ----------
    text
        Document to inspect.
    line_length
        Prose limit.
    code_line_length
        Limit applied inside fenced code.

    Returns
    -------
    tuple[int, ...]
        Zero-based line numbers in document order.
    """
    lines = text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    fence_flags = _fence_line_flags(lines)
    table_flags = _table_line_flags(lines)
    exempt = _exempt_lines(lines)
    offending: list[int] = []
    for index, line in enumerate(lines):
        if index in exempt or table_flags[index] or _HEADING.match(line):
            continue
        limit = code_line_length if fence_flags[index] else line_length
        if _is_too_long(line, limit):
            offending.append(index)
    return tuple(offending)


def insert_exemptions(
    text: str,
    *,
    line_length: int = DEFAULT_LINE_LENGTH,
    code_line_length: int = DEFAULT_CODE_LINE_LENGTH,
) -> str:
    """Bracket every offending top-level block in an MD013 exemption.

    One disable/enable pair wraps the smallest paragraph, list, blockquote,
    table, or fenced block that contains an over-long line. The pair is placed
    at column zero with blank lines around it, which survives the formatter's
    later reflow. Running the function twice changes nothing because lines
    between an existing pair are skipped.

    Parameters
    ----------
    text
        Document to adjust.
    line_length
        Prose limit.
    code_line_length
        Limit applied inside fenced code.

    Returns
    -------
    str
        Document with bounded exemptions and one trailing newline.
    """
    lines = text.replace("\r\n", "\n").replace("\r", "\n").rstrip("\n").split("\n")
    fence_flags = _fence_line_flags(lines)
    table_flags = _table_line_flags(lines)
    exempt = _exempt_lines(lines)
    ranges, owner = _block_ranges(lines, fence_flags, table_flags)

    targets: set[int] = set()
    for index, line in enumerate(lines):
        if index in exempt or table_flags[index] or _HEADING.match(line):
            continue
        limit = code_line_length if fence_flags[index] else line_length
        if _is_too_long(line, limit) and owner[index] >= 0:
            targets.add(owner[index])

    for block in sorted(targets, reverse=True):
        start, end = ranges[block]
        before: list[str] = []
        if start > 0 and not _is_blank(lines[start - 1]):
            before.append("")
        after: list[str] = []
        if end + 1 < len(lines) and not _is_blank(lines[end + 1]):
            after.append("")
        lines = [
            *lines[:start],
            *before,
            DISABLE_M013,
            "",
            *lines[start : end + 1],
            "",
            ENABLE_M013,
            *after,
            *lines[end + 1 :],
        ]
    return "\n".join(lines).rstrip("\n") + "\n"


def _write(path: Path, text: str) -> None:
    """Write one converted document with ``\\n`` newlines.

    Parameters
    ----------
    path
        Destination file.
    text
        Document content.
    """
    path.write_text(text.rstrip("\n") + "\n", encoding="utf-8", newline="\n")


def _read(path: Path) -> str:
    """Read one document and normalize its newlines.

    Parameters
    ----------
    path
        File to read.

    Returns
    -------
    str
        Content with ``\\n`` newlines.
    """
    return (
        path.read_text(encoding="utf-8").replace("\r\n", "\n").replace("\r", "\n")
    )


def vendor(
    config: VendorConfig,
    *,
    format_files: Callable[[Sequence[Path]], None] | None = None,
) -> tuple[Path, ...]:
    """Convert, format, and write every mapped guide.

    Parameters
    ----------
    config
        Import description. Its arguments are validated before any file is
        written.
    format_files
        Optional callable that rewrites the supplied paths in place. The front
        end supplies a cuprum-backed ``mdtablefix`` runner; tests supply a
        deterministic double.

    Returns
    -------
    tuple[Path, ...]
        Written paths in mapping order.

    Raises
    ------
    VendorError
        If an argument is unusable, a source already carries the note, or the
        formatter does not reach a fixed point.
    """
    validate(config)
    written: list[Path] = []
    converted: list[str] = []
    for source_name, output_name in config.mappings:
        source = config.source_directory / source_name
        text = convert(_read(source), config, source_name)
        target = config.output_directory / output_name
        _write(target, text)
        written.append(target)
        converted.append(text)

    if format_files is None:
        for path, text in zip(written, converted, strict=True):
            _write(path, insert_exemptions(text))
        return tuple(written)

    format_files(written)
    exempted = [
        insert_exemptions(_read(path)) for path in written
    ]
    for path, text in zip(written, exempted, strict=True):
        _write(path, text)

    format_files(written)
    for path, text in zip(written, exempted, strict=True):
        if _read(path) != text:
            _fail(f"formatter did not reach a fixed point for {path}")
    return tuple(written)
